#!/usr/bin/env python3
"""Generate checked-in Claude and Codex discovery from registered repo skills."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'agents'))
from _repo_paths import manifest_paths, repo_path

MARKER = '<!-- Generated by PyAutoBrain/bin/project_discovery.py; do not edit. -->'
ORGAN_NAMES = {'PyAutoBrain', 'PyAutoMind', 'PyAutoHeart', 'PyAutoHands', 'PyAutoMemory', 'autolens_profiling'}
SURFACES = ('.claude/commands', '.claude/skills', '.codex/skills')
VALID = re.compile(r'[a-z][a-z0-9-]{0,63}\Z')


def slug(value: str) -> str:
    return value.lower().replace('_', '-')


def frontmatter(path: Path) -> dict[str, str]:
    lines = path.read_text().splitlines()
    if not lines or lines[0] != '---':
        return {}
    fields = {}
    for line in lines[1:]:
        if line == '---':
            return fields
        if ':' in line and not line.startswith(' '):
            key, value = line.split(':', 1)
            fields[key] = value.strip().strip('"\'')
    return {}


def adapter(name: str, description: str, link: str) -> str:
    if not VALID.fullmatch(name):
        raise ValueError(f'invalid Codex skill name: {name}')
    if not description or '\n' in description:
        raise ValueError(f'{name}: missing/invalid description')
    return (f'---\nname: {name}\ndescription: {json.dumps(description, ensure_ascii=False)}\n---\n'
            f'{MARKER}\n\nRead and follow the canonical skill: [SKILL]({link}).\n')


def expected(repo: str, path: Path) -> dict[str, tuple[str, str]]:
    """Relative path -> (symlink, target) or (file, contents)."""
    skills = path / 'skills'
    result = {}
    if not skills.is_dir():
        return result
    prefix = slug(repo)
    def add(key: str, value: tuple[str, str]) -> None:
        if key in result:
            raise ValueError(f'{repo}: duplicate discovery path: {key}')
        result[key] = value
    for entry in sorted(skills.iterdir()):
        if entry.is_dir() and (entry / 'SKILL.md').is_file():
            name = entry.name
            add(f'.claude/skills/{name}', ('symlink', f'../../skills/{name}'))
            body = entry / 'SKILL.md'
            if repo in ORGAN_NAMES:
                codex_name = frontmatter(body).get('name', '')
                if VALID.fullmatch(codex_name):
                    add(f'.codex/skills/{codex_name}', ('symlink', f'../../skills/{name}'))
            else:
                codex_name = f'{prefix}-{slug(name)}'
                meta = frontmatter(body)
                add(f'.codex/skills/{codex_name}/SKILL.md', ('file', adapter(
                    codex_name, meta.get('description', ''), f'../../../skills/{name}/SKILL.md')))
            command = entry / f'{name}.md'
            if command.is_file():
                add(f'.claude/commands/{name}.md', ('symlink', f'../../skills/{name}/{name}.md'))
        elif entry.is_file() and entry.suffix == '.md' and entry.name != 'README.md':
            meta = frontmatter(entry)
            if not meta and not entry.name.startswith('_'):
                continue  # supporting prose is not a skill
            # Existing flat Claude skill links include private helpers.
            add(f'.claude/skills/{entry.name}', ('symlink', f'../../skills/{entry.name}'))
            if entry.name.startswith('_'):
                continue
            if not meta.get('name') or not meta.get('description'):
                raise ValueError(f'{entry}: public flat skill requires name and description')
            name = entry.stem
            add(f'.claude/commands/{name}.md', ('symlink', f'../../skills/{entry.name}'))
            codex_name = f'{prefix}-{slug(meta["name"])}'
            add(f'.codex/skills/{codex_name}/SKILL.md', ('file', adapter(
                codex_name, meta['description'], f'../../../skills/{entry.name}')))
    return result


def actual(path: Path) -> dict[str, tuple[str, str]]:
    found = {}
    for surface in SURFACES:
        base = path / surface
        if not base.is_dir():
            continue
        for child in base.iterdir():
            key = str(child.relative_to(path))
            if child.is_symlink():
                found[key] = ('symlink', os.readlink(child))
            elif child.is_dir() and surface == '.codex/skills':
                body = child / 'SKILL.md'
                if body.is_file() and MARKER in body.read_text():
                    found[str(body.relative_to(path))] = ('file', body.read_text())
                else:
                    found[key] = ('protected', '')
            else:
                found[key] = ('protected', '')
    return found


def run(root: Path, names: list[str], write: bool) -> int:
    registry = manifest_paths(root)
    selected = names or list(registry)
    if names:
        unknown = set(names) - set(registry)
        if unknown:
            raise ValueError(f'unregistered repository: {", ".join(sorted(unknown))}')
    plans = {}
    owners = {}
    for name in registry:
        path = repo_path(root, name)
        if not path.is_dir() or not (path / 'skills').is_dir():
            continue
        wanted = expected(name, path)
        for rel in wanted:
            if rel.startswith('.codex/skills/'):
                codex_name = rel.split('/')[2]
                prior = owners.setdefault(codex_name, name)
                if prior != name:
                    raise ValueError(f'Codex skill collision {codex_name}: {prior}, {name}')
        if name in selected:
            plans[name] = (path, wanted)
    # Refuse the complete write if any destination is user-owned.
    def protected_conflicts(path: Path, wanted: dict[str, tuple[str, str]]) -> list[str]:
        present = actual(path)
        conflicts = []
        for key in wanted:
            if key in present and present[key][0] == 'protected':
                conflicts.append(key)
            parent = Path(key).parent
            while str(parent) != '.':
                existing = path / parent
                if existing.is_symlink() and str(parent) not in present:
                    conflicts.append(str(parent))
                    break
                if existing.exists() and not existing.is_dir():
                    conflicts.append(str(parent))
                    break
                if str(parent) in present and present[str(parent)][0] == 'protected':
                    conflicts.append(str(parent))
                    break
                parent = parent.parent
        return sorted(set(conflicts))
    conflicts_by_repo = {name: protected_conflicts(path, wanted)
                         for name, (path, wanted) in plans.items()}
    has_conflict = any(conflicts_by_repo.values())
    drift = False
    for name, (path, wanted) in plans.items():
        present = actual(path)
        managed = {key: value for key, value in present.items() if value[0] != 'protected'}
        conflicts = sorted(key for key in wanted if key in present and present[key][0] == 'protected')
        missing = sorted(set(wanted) - set(managed))
        stale = sorted(set(managed) - set(wanted))
        changed = sorted(key for key in set(wanted) & set(managed) if wanted[key] != managed[key])
        if conflicts or missing or stale or changed:
            drift = True
            print(f'{"CONFLICT" if conflicts else "DRIFT"}: {name}: ' + ', '.join(
                f'{kind} {items}' for kind, items in [('protected', conflicts), ('missing', missing), ('stale', stale), ('changed', changed)] if items))
        else:
            print(f'OK: {name}')
        if not write or has_conflict:
            continue
        for rel in stale + changed:
            item = path / rel
            item.unlink()
            if item.parent != path and not any(item.parent.iterdir()):
                item.parent.rmdir()
        for rel in missing + changed:
            kind, data = wanted[rel]
            item = path / rel
            item.parent.mkdir(parents=True, exist_ok=True)
            if kind == 'symlink':
                item.symlink_to(data)
            else:
                item.write_text(data)
    return 2 if has_conflict and write else int(drift and not write)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=('write', 'check'))
    parser.add_argument('repos', nargs='*')
    parser.add_argument('--root', type=Path, default=Path(os.environ.get('PYAUTO_ROOT', '.')))
    args = parser.parse_args()
    try:
        return run(args.root, args.repos, args.mode == 'write')
    except (ValueError, OSError) as error:
        print(f'project discovery: {error}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
